import { test, expect } from '@playwright/test'

test('scan, publish, filter, evidence, bookmark, notes and reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('DEMO MODE', { exact: false })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Your next opportunity starts here.' })).toBeVisible()
  await page.getByRole('button', { name: 'Run a full scan' }).click()
  await expect(page.getByText(/Showing the previous completed snapshot/)).toBeVisible()
  await expect(page.locator('.opportunity')).toHaveCount(2, { timeout: 15000 })
  await page.getByRole('textbox', { name: 'Search opportunities' }).fill('cloud')
  await expect(page.locator('.opportunity')).toHaveCount(1)
  await page.getByRole('button', { name: 'View evidence' }).click()
  await expect(page.getByRole('heading', { name: 'Field-level evidence' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Personal notes' }).fill('<script>alert("test")</script> My saved notes')
  await page.getByLabel('Bookmarked', { exact: true }).check()
  const savedNotes = page.waitForResponse(r => r.url().endsWith('/state') && r.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Save notes & preferences' }).click()
  expect((await savedNotes).ok()).toBeTruthy()
  await expect(page.locator('dialog').getByText('Notes and preferences saved', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Application status', exact: true }).selectOption('preparing')
  await page.getByRole('textbox', { name: 'Personal reminder date', exact: true }).fill('2027-01-02')
  await page.getByRole('button', { name: 'Save tracking', exact: true }).click()
  await expect(page.getByText('Tracking saved.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Close detail' }).click()
  await page.reload()
  await expect(page.locator('.opportunity')).toHaveCount(1)
  await page.getByRole('button', { name: 'View evidence' }).click()
  await expect(page.getByRole('textbox', { name: 'Personal notes' })).toHaveValue('<script>alert("test")</script> My saved notes')
  await expect(page.getByLabel('Bookmarked', { exact: true })).toBeChecked()
  await expect(page.getByRole('combobox', { name: 'Application status', exact: true })).toHaveValue('preparing')
  await page.getByRole('button', { name: 'Close detail' }).click()
  await page.getByRole('navigation').getByRole('button', { name: 'Tracker', exact: false }).click()
  await expect(page.locator('.tracker-row')).toHaveCount(1)
  const calendar = await page.request.get('/api/calendar.ics')
  expect(await calendar.text()).toContain('DTSTART;VALUE=DATE:20270102')
  await page.getByRole('navigation').getByRole('button', { name: 'Digest', exact: false }).click()
  await expect(page.getByRole('heading', { name: 'Your week in opportunities.' })).toBeVisible()
  await expect(page.locator('.digest-row')).toHaveCount(2)
  await page.getByRole('navigation').getByRole('button', { name: /Discover$/ }).click()
  await page.getByRole('textbox', { name: 'Search opportunities' }).fill('')
  await expect(page.locator('.opportunity')).toHaveCount(2)
  await page.screenshot({ path: '../data/dashboard-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Good things, on your radar.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../data/dashboard-mobile.png', fullPage: true })
})

test('source and schedule controls persist without silently enabling scans', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Settings', exact: false }).click()
  await page.getByRole('combobox', { name: 'Scan schedule', exact: true }).selectOption('manual')
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await expect(page.getByText('Settings saved.', { exact: false })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Scan schedule', exact: true })).toHaveValue('manual')
  await expect(page.getByLabel('Enable automatic scans on this PC')).not.toBeChecked()
  await page.getByRole('button', { name: 'Sources', exact: false }).first().click()
  const update = page.waitForResponse(r => r.url().endsWith('/sources/demo-cloud') && r.request().method() === 'PUT')
  await page.getByLabel('Enable DEMO Cloud', { exact: true }).uncheck()
  await update
  await page.reload()
  await expect(page.getByLabel('Enable DEMO Cloud', { exact: true })).not.toBeChecked()
})

test('dynamic discovery streams real fixture stages, pauses, resumes and replays', async ({ page, request }) => {
  await page.goto('/?view=Live+discovery')
  await expect(page.getByRole('heading', { name: 'A radar that keeps exploring.' })).toBeVisible()
  await page.getByText('Campaign scope and budgets', { exact: true }).click()
  await page.getByLabel('Also check seed sources').uncheck()
  await page.getByLabel('Discover GitHub repositories').uncheck()
  await page.getByLabel('Page limit', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Start discovery', exact: true }).click()
  await expect(page.getByRole('log').getByText('fetch started', { exact: true })).toBeVisible({ timeout: 15000 })
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toBeVisible()
  const pending = await (await request.get('/api/results?publication_state=provisional')).json()
  expect(pending.items.some((i: any) => i.discovery_url.includes('unlisted.example'))).toBeTruthy()
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await expect(page.getByRole('log').getByText('campaign completed', { exact: true })).toBeVisible({ timeout: 15000 })
  const events = await (await request.get('/api/discovery/events')).json()
  const cursor = events[Math.floor(events.length / 2)].id
  const replayed: number = await page.evaluate((after: number) => new Promise(resolve => {
    const stream = new EventSource('/api/discovery/stream?after=' + after)
    stream.onmessage = e => { stream.close(); resolve(JSON.parse(e.data).id) }
  }), cursor)
  expect(replayed).toBeGreaterThan(cursor)
  await page.getByRole('button', { name: 'Alert rules', exact: true }).click()
  await page.getByLabel('Rule name', { exact: true }).fill('Cafe discoveries')
  await page.getByRole('button', { name: 'Create alert rule' }).click()
  await expect(page.getByText('Cafe discoveries', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../data/discovery-mobile.png', fullPage: true })
})

